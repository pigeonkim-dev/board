-- 자기소개를 더한다.
--
-- nullable 로 둔다. 자기소개는 안 써도 되는 값이다.
-- NOT NULL 로 두면 기존 회원 4명에게 빈 문자열이라도 넣어야 하고,
-- 그러면 "안 쓴 것"과 "빈 문자열을 쓴 것"이 구분되지 않는다.
--
-- 256자는 Comment.content(500자)보다 짧게 잡은 값이다.
--
-- imageUrl 은 여기 넣지 않는다. 업로드가 B6-6 이고, 저장소를 파일/S3 중에
-- 고를 수 있게 만들 예정이라 컬럼만 먼저 만들어 두면 몇 달간 아무도 안 쓴다.
-- location 도 넣지 않는다. 사용자가 입력하는 값이 아니라 자동으로 알아낼 값이라
-- 텍스트 칸으로 만들어 두면 나중에 걸림돌이 된다.

ALTER TABLE profiles ADD COLUMN bio varchar(256);
